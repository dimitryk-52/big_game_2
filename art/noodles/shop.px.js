// Лапшичная для экрана «Лапши» на ТВ (src/tv/NoodleTv.tsx, стили .nood-row в src/styles/tv.css).
// Сборка: node ~/.claude/skills/pxl-pixel-art/bin/pxl.js build art/noodles/shop.px.js
// → out/scenes/noodle_wall.png и out/sprites/noodle_counter.png в src/img/noodles/.
//
// noodle_wall — стена за прилавком: идёт фоном «cover» от верха, на ТВ видно ~верхние 100 px,
//   поэтому всё важное (норэн, фонари, таблички) — в верхней части.
// noodle_counter — плитка прилавка, повторяется по горизонтали внизу; на ней стоят стопки мисок.

pal({
  k: "#1a0f0c",
  d: "#2e1a12", D: "#452819", b: "#5e3a22", B: "#7c4e2c",     // тёмное дерево
  p: "#8a6a48", P: "#a8865c", c: "#c4a274", C: "#d8bc8c",     // штукатурка
  h: "#a87840", H: "#c89858", j: "#e0b878", J: "#f2d49a",     // хиноки (прилавок)
  n: "#1c2448", N: "#2c3a6c", v: "#41558f",                   // норэн, индиго
  w: "#f2ead8", W: "#c9bfa8",                                 // белое, бумага
  i: "#2a1a14",                                               // тушь
  r: "#a82428", R: "#d8403a", o: "#ff8a5a", y: "#ffd27a",     // фонари
})
ramps("kdDbB", "pPcC", "hHjJ", "nNv", "rRoy", "Ww")

// бумажный фонарь-тётин: красный, с тёмными ободками и иероглифом-кругом
sprite("_lantern", { w: 16, h: 26 },
  rect(5, 0, 6, 1, "k"), vline(7, 0, 2, "k"),
  rect(3, 2, 10, 2, "d"), rect(3, 22, 10, 2, "d"),
  ellipse(7.5, 13, 7, 9, "R"),
  clip([0, 4, 6, 18], ellipse(7.5, 13, 7, 9, "o")),
  clip([11, 4, 5, 18], ellipse(7.5, 13, 7, 9, "r")),
  (c) => { for (const y of [7, 11, 15, 19]) for (let x = 1; x < 15; x++) if (c.is(x, y, "Ro")) c.px(x, y, c.is(x, y, "o") ? "R" : "r") },
  ring(7, 13, 3, "y"), px(7, 13, "y"),
  rect(6, 24, 4, 2, "R"),
)

// табличка меню: бумажная полоска с мазками туши и красной печатью
sprite("_tag", { w: 9, h: 30 },
  rect(0, 0, 9, 30, "w"), rect(8, 0, 1, 30, "W"), rect(0, 29, 9, 1, "W"),
  (c) => {
    const r = c.rng(1)
    let y = 3
    while (y < 21) { const h = 2 + Math.floor(r() * 3); c.rect(3, y, 3, h, "i"); if (r() < 0.5) c.px(2, y + 1, "i"); y += h + 2 }
  },
  rect(3, 24, 3, 3, "r"),
)

scene("noodle_wall", { w: 384, h: 144, bg: "c" },
  grad(0, 0, 384, 144, "PcC", "v", 0.6),
  // нижняя обшивка из досок
  rect(0, 96, 384, 48, "b"),
  (c) => { for (let x = 0; x < 384; x += 12) c.vline(x, 96, 48, "D") },
  rect(0, 96, 384, 2, "B"), rect(0, 98, 384, 1, "d"),
  // балка и столбы
  rect(0, 0, 384, 9, "D"), rect(0, 8, 384, 1, "d"), rect(0, 1, 384, 1, "b"),
  rect(0, 0, 14, 144, "D"), rect(12, 0, 2, 144, "d"), rect(2, 0, 2, 144, "b"),
  rect(370, 0, 14, 144, "D"), rect(370, 0, 2, 144, "d"), rect(380, 0, 2, 144, "b"),
  // полка с мисками справа и слева
  rect(24, 74, 92, 4, "B"), rect(24, 78, 92, 1, "d"), rect(268, 74, 92, 4, "B"), rect(268, 78, 92, 1, "d"),
  (c) => {
    for (const x0 of [30, 274]) for (let k = 0; k < 6; k++) {
      const x = x0 + k * 14
      c.ellipse(x + 5, 70, 6, 2, "w"); c.rect(x, 70, 11, 3, "w"); c.hline(x + 1, 73, 9, "W"); c.hline(x + 2, 71, 7, "r")
    }
  },
  // таблички меню
  (c) => { for (let k = 0; k < 6; k++) { c.stamp("_tag", 56 + k * 11, 30, { seed: k }); c.stamp("_tag", 264 + k * 11, 30, { seed: k + 9 }) } },
  // норэн: штанга и четыре полотнища с белой миской и палочками
  rect(128, 10, 128, 3, "B"), rect(126, 10, 2, 3, "k"), rect(256, 10, 2, 3, "k"),
  (c) => {
    for (let k = 0; k < 4; k++) {
      const x = 130 + k * 31
      c.rect(x, 13, 29, 46, "N"); c.rect(x, 13, 29, 2, "n"); c.vline(x + 28, 13, 46, "n"); c.rect(x, 57, 29, 2, "v")
    }
    // эмблема: миска с лапшой и палочки, на стыке двух средних полотнищ
  },
  clip([170, 30, 44, 20], ellipse(192, 30, 15, 13, "w")),
  ellipse(192, 30, 15, 4, "w"), ellipse(192, 30, 13, 3, "N"), hline(181, 29, 22, "w"), hline(183, 31, 18, "w"),
  line(200, 14, 186, 28, "w"), line(205, 15, 190, 28, "w"), rect(189, 44, 7, 2, "w"),
  vline(191, 13, 46, "n"), vline(192, 13, 46, "n"),
  // фонари и тёплое пятно света вокруг них
  layer("glow", { light: true, density: 0.5 }, circ(36, 26, 26, "k"), circ(348, 26, 26, "k")),
  layer("glow2", { light: true }, circ(36, 26, 15, "k"), circ(348, 26, 15, "k")),
  stamp("_lantern", 28, 12), stamp("_lantern", 340, 12),
)

// плитка прилавка 32×30: столешница из хиноки, тень под кромкой, передняя стенка из досок
sprite("noodle_counter", { w: 32, h: 30 },
  rect(0, 0, 32, 1, "J"), rect(0, 1, 32, 5, "j"), rect(0, 6, 32, 1, "H"), rect(0, 7, 32, 1, "h"),
  hline(3, 3, 9, "H"), hline(18, 2, 7, "H"), hline(26, 4, 5, "H"),
  rect(0, 8, 32, 2, "k"),
  rect(0, 10, 32, 20, "b"), rect(0, 10, 32, 1, "D"),
  vline(15, 10, 20, "d"), vline(31, 10, 20, "d"), vline(16, 10, 20, "B"), vline(0, 10, 20, "B"),
  hline(3, 16, 8, "D"), hline(20, 21, 9, "D"), hline(5, 25, 6, "D"),
)
